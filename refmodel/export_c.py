"""Export NVFP4 matmul cases as a C header for the M4 v0 bare-metal test (hw/tests/nvfp4_v0.c)."""
import struct
import sys
from pathlib import Path
import numpy as np
from formats import e4m3_decode
from quant import quantize, BLOCK
from hw_dot import code_to_int, hw_matmul_v0

M = N = 16
MAX_NB = 4
CASES = (("k16", 16, 101), ("k64", 64, 202))  # (name, K, seed)


def make_case(k, seed):
    """Deterministic A (M x K) and B^T (N x K) with varied per-block magnitudes."""
    rng = np.random.default_rng(seed)
    nb = k // BLOCK

    def gen(rows):
        x = rng.standard_normal((rows, nb, BLOCK)) * 2.0 ** rng.integers(-3, 4, size=(rows, nb, 1))
        return x.reshape(rows, k)

    return quantize(gen(M)), quantize(gen(N))


def f32_bits(x):
    return struct.unpack("<I", struct.pack("<f", float(np.float32(x))))[0]


def _hexf(x):
    return float(x).hex() + "f" if np.isfinite(x) else repr(float(x))


def _fmt(vals, per_line, fn):
    vals = list(vals)
    lines = []
    for i in range(0, len(vals), per_line):
        lines.append("    " + ", ".join(fn(v) for v in vals[i:i + per_line]) + ",")
    return "\n".join(lines)


def case_arrays(qa, qb):
    nb = qa.codes.shape[1] // BLOCK
    ia = code_to_int(qa.codes).reshape(M, nb, BLOCK)  # [i, kb, k]
    ib = code_to_int(qb.codes).reshape(N, nb, BLOCK)  # [j, kb, k]
    a_blk = np.zeros((MAX_NB, M, BLOCK), np.int32)    # [kb][i][k]
    b_blk = np.zeros((MAX_NB, BLOCK, N), np.int32)    # [kb][k][j]  (K x N, row = k)
    a_blk[:nb] = ia.transpose(1, 0, 2)
    b_blk[:nb] = ib.transpose(1, 2, 0)
    sa = np.zeros((M, MAX_NB), np.float32)
    sb = np.zeros((MAX_NB, N), np.float32)
    sa[:, :nb] = e4m3_decode(qa.scales)
    sb[:nb, :] = e4m3_decode(qb.scales).T
    sums, out = hw_matmul_v0(qa, qb)
    isum = np.zeros((MAX_NB, M, N), np.int32)         # [kb][i][j]
    isum[:nb] = sums.transpose(2, 0, 1)
    return nb, a_blk, b_blk, sa, sb, isum, out


def export_c_header(path):
    out = [
        "// Generated by refmodel/export_c.py. Do not edit.",
        "// NVFP4 v0 test vectors: A (16xK) times B (Kx16), blocks of 16 along K.",
        "// A/B hold E2M1 values decoded to doubled signed integers (int8).",
        "#ifndef NVFP4_V0_DATA_H",
        "#define NVFP4_V0_DATA_H",
        "#include <stdint.h>",
        f"#define NVFP4_MAX_NB {MAX_NB}",
        f"#define NVFP4_NCASES {len(CASES)}",
        "typedef struct {",
        "  int nb;                                   // number of K blocks (K = 16*nb)",
        "  int8_t A[NVFP4_MAX_NB][16][16];           // [kb][i][k]",
        "  int8_t B[NVFP4_MAX_NB][16][16];           // [kb][k][j]",
        "  float sA[16][NVFP4_MAX_NB];               // E4M3 scale values [i][kb]",
        "  float sB[NVFP4_MAX_NB][16];               // E4M3 scale values [kb][j]",
        "  float tA, tB;                             // tensor scales",
        "  int32_t isum[NVFP4_MAX_NB][16][16];       // expected block sums [kb][i][j]",
        "  uint32_t out_bits[16][16];                // expected float32 output, as bit patterns",
        "} nvfp4_case_t;",
        "",
        "static const nvfp4_case_t nvfp4_cases[NVFP4_NCASES] __attribute__((aligned(64))) = {",
    ]
    for name, k, seed in CASES:
        qa, qb = make_case(k, seed)
        nb, a_blk, b_blk, sa, sb, isum, o = case_arrays(qa, qb)
        out.append(f"  {{ // {name}: K={k}, seed={seed}")
        out.append(f"    {nb},")
        out.append("    {")
        out.append(_fmt(a_blk.ravel(), 16, lambda v: str(int(v))))
        out.append("    },")
        out.append("    {")
        out.append(_fmt(b_blk.ravel(), 16, lambda v: str(int(v))))
        out.append("    },")
        out.append("    {")
        out.append(_fmt(sa.ravel(), 4, _hexf))
        out.append("    },")
        out.append("    {")
        out.append(_fmt(sb.ravel(), 4, _hexf))
        out.append("    },")
        out.append(f"    {_hexf(qa.tensor_scale[0])}, {_hexf(qb.tensor_scale[0])},")
        out.append("    {")
        out.append(_fmt(isum.ravel(), 8, lambda v: str(int(v))))
        out.append("    },")
        out.append("    {")
        out.append(_fmt(o.ravel(), 8, lambda v: f"0x{f32_bits(v):08x}u"))
        out.append("    },")
        out.append("  },")
    out += ["};", "#endif", ""]
    Path(path).write_text("\n".join(out), newline="\n")


if __name__ == "__main__":
    export_c_header(sys.argv[1] if len(sys.argv) > 1 else "hw/tests/nvfp4_v0_data.h")
