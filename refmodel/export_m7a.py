"""Export M7.A Spike test data headers (hw/tests/m7a_*_data.h) from the refmodel.

  python refmodel/export_m7a.py int8  hw/tests/m7a_int8_data.h
  python refmodel/export_m7a.py fp32  hw/tests/m7a_fp32_data.h
  python refmodel/export_m7a.py mx fp8 hw/tests/m7a_mx_fp8_data.h     (and: mx fp4 ...)
  python refmodel/export_m7a.py nvfp4 hw/tests/nvfp4_e2e_m7a_data.h   (large-K NVFP4 case, nvfp4_e2e_mnk.c layout)
The inputs come from accuracy_sweep.make_inputs so the Spike checks cover the same distributions as the sweep.
"""
import struct
import sys
from pathlib import Path
import numpy as np
import accuracy_sweep as sw
import int8
import mx
import hw_models as hm


def _fmt(vals, per_line, fn):
    vals = list(vals)
    return "\n".join("    " + ", ".join(fn(v) for v in vals[i:i + per_line]) + "," for i in range(0, len(vals), per_line))


def f32_bits(x):
    return struct.unpack("<I", struct.pack("<f", float(np.float32(x))))[0]


# ----------------------------------------------------------------------------- INT8
INT8_CASES = [   # (dist, M, N, K, seed): shapes the stock software tiles in different ways
    ("gaussian", 64, 64, 1024, 0),
    ("laplace", 48, 32, 2048, 1),
    ("outlier", 64, 64, 4096, 2),
    ("student_t3", 32, 64, 1024, 3),
    ("extreme", 16, 16, 16384, 0),     # all +-127: the largest possible accumulation (16384 * 127 * 127)
]


def int8_case(dist, M, N, K, seed):
    if dist == "extreme":
        rng = np.random.default_rng(99)
        qa = np.where(rng.integers(0, 2, (M, K)) == 1, 127, -127).astype(np.int8)
        qb = np.where(rng.integers(0, 2, (K, N)) == 1, 127, -127).astype(np.int8)
        qa[0, :] = 127
        qb[:, 0] = 127                                  # C[0][0] = K * 127 * 127, the maximum
        qa[1, :], qb[:, 1] = 127, -127                  # C[1][1] = -K * 127 * 127
    else:
        a, b = sw.make_inputs(dist, K, seed, M, N)
        qa, qb = int8.quantize(a).q, int8.quantize(b).q
    return qa, qb, int8.int32_matmul(qa, qb)


def export_int8(path):
    lines = ["// Generated by refmodel/export_m7a.py int8. Do not edit.", "#include <stdint.h>",
             "typedef struct { int M, N, K; const int8_t *A; const int8_t *B; const int32_t *C; } case_t;",
             f"#define NCASES {len(INT8_CASES)}"]
    info = []
    for n, (dist, M, N, K, seed) in enumerate(INT8_CASES):
        qa, qb, c = int8_case(dist, M, N, K, seed)
        lines += [f"static const int8_t A{n}[{M * K}] = {{", _fmt(qa.ravel(), 32, lambda v: str(int(v))), "};",
                  f"static const int8_t B{n}[{K * N}] = {{", _fmt(qb.ravel(), 32, lambda v: str(int(v))), "};",
                  f"static const int32_t C{n}[{M * N}] = {{", _fmt(c.ravel(), 16, lambda v: str(int(v))), "};"]
        info.append(f"case {n}: {dist} M={M} N={N} K={K} max|C|={int(np.abs(c).max())}")
    lines.append("static const case_t cases[NCASES] = {")
    lines += [f"    {{ {M}, {N}, {K}, A{n}, B{n}, C{n} }}," for n, (_, M, N, K, _) in enumerate(INT8_CASES)]
    lines += ["};", ""]
    Path(path).write_text("\n".join(lines), newline="\n")
    print(f"wrote {path}: " + "; ".join(info))


# ----------------------------------------------------------------------------- FP32
FP32_CASES = [
    ("gaussian", 64, 64, 1024, 0),
    ("outlier", 64, 64, 1024, 1),
    ("student_t3", 32, 32, 4096, 2),
    ("laplace", 16, 16, 16384, 3),
    ("gaussian", 20, 28, 260, 4),      # shapes that are not multiples of 16 (4 x 4 mesh: multiples of 4 are enough)
]


def export_fp32(path):
    lines = ["// Generated by refmodel/export_m7a.py fp32. Do not edit.", "#include <stdint.h>",
             "typedef struct { int M, N, K; const uint32_t *A; const uint32_t *B; const uint32_t *C_sep; const uint32_t *C_fused; } case_t;",
             f"#define NCASES {len(FP32_CASES)}"]
    info = []
    for n, (dist, M, N, K, seed) in enumerate(FP32_CASES):
        a, b = sw.make_inputs(dist, K, seed, M, N)
        a32, b32 = a.astype(np.float32), b.astype(np.float32)
        sep = hm.fp32_h(a32, b32).astype(np.float32)
        fused = hm.fp32_fused_h(a32, b32).astype(np.float32)
        to_bits = lambda x: x.view(np.uint32).ravel()
        lines += [f"static const uint32_t A{n}[{M * K}] = {{", _fmt(to_bits(a32), 8, lambda v: f"0x{int(v):08x}u"), "};",
                  f"static const uint32_t B{n}[{K * N}] = {{", _fmt(to_bits(b32), 8, lambda v: f"0x{int(v):08x}u"), "};",
                  f"static const uint32_t CS{n}[{M * N}] = {{", _fmt(to_bits(sep), 8, lambda v: f"0x{int(v):08x}u"), "};",
                  f"static const uint32_t CF{n}[{M * N}] = {{", _fmt(to_bits(fused), 8, lambda v: f"0x{int(v):08x}u"), "};"]
        info.append(f"case {n}: {dist} M={M} N={N} K={K}, separate-vs-fused differ in {int((sep != fused).sum())}/{M * N}")
    lines.append("static const case_t cases[NCASES] = {")
    lines += [f"    {{ {M}, {N}, {K}, A{n}, B{n}, CS{n}, CF{n} }}," for n, (_, M, N, K, _) in enumerate(FP32_CASES)]
    lines += ["};", ""]
    Path(path).write_text("\n".join(lines), newline="\n")
    print(f"wrote {path}: " + "; ".join(info))



# ----------------------------------------------------------------------------- MX (FP8 E4M3 / FP4 E2M1)
def mx_cases(fmt):
    """>= 20 matrices per format: every sweep distribution at K >= 1024, small multi-tile shapes, OCP-recipe overflow data,
    and wide-dynamic-range data (E8M0 clamps, product flush). (name, dist, M, N, K, seed, recipe)."""
    big = [(64, 64, 1024), (32, 32, 2048), (32, 32, 4096) if fmt == "fp4" else (16, 16, 4096)]
    small = [(32, 64, 160), (64, 32, 96)] if fmt == "fp4" else [(16, 48, 160), (48, 16, 96)]
    cases = []
    for dist in sw.DISTS:
        for (M, N, K) in big:
            cases.append((f"{dist}_{M}x{N}x{K}", dist, M, N, K, 1, "branch"))
    for dist in sw.DISTS:
        for (M, N, K) in small:
            cases.append((f"{dist}_{M}x{N}x{K}", dist, M, N, K, 2, "branch"))
    cases.append(("ocp_gaussian_32x32x256", "gaussian", 32, 32, 256, 3, "ocp"))
    cases.append(("ocp_laplace_64x64x1024", "laplace", 64, 64, 1024, 3, "ocp"))
    cases.append(("wide_range_32x32x1024", "wide", 32, 32, 1024, 4, "branch"))
    cases.append(("wide_range_ocp_32x32x512", "wide", 32, 32, 512, 5, "ocp"))
    return cases


def mx_inputs(dist, M, N, K, seed):
    if dist != "wide":
        return sw.make_inputs(dist, K, seed, M, N)
    rng = np.random.default_rng([seed, K, 77])
    a = rng.standard_t(3, (M, K)) * 2.0 ** rng.integers(-30, 31, (M, 1))
    b = rng.standard_t(3, (K, N)) * 2.0 ** rng.integers(-30, 31, (1, N))
    return a, b


def rtz_fmt(x, e_bits, m_bits):
    """CONTROL ONLY: the accumulator rounding changed from RNE to round-toward-zero (truncation)."""
    x = np.asarray(x, np.float32)
    if (e_bits, m_bits) == (8, 23):
        return x
    bias = (1 << (e_bits - 1)) - 1
    emin, emax = 1 - bias, bias
    ax = np.abs(x)
    drop = 23 - m_bits
    tr = ((ax.view(np.uint32) >> np.uint32(drop)) << np.uint32(drop)).view(np.float32)
    q = 2.0 ** (emin - m_bits)
    sub = (np.floor(ax.astype(np.float64) / q) * q).astype(np.float32)
    res = np.where(ax < np.float32(2.0 ** emin), sub, tr)
    res = np.where(res.astype(np.float64) >= 2.0 ** (emax + 1), np.float32(np.inf), res)
    return np.where(np.isfinite(x), np.where((x < 0) & (res != 0), -res, res), x).astype(np.float32)


def export_mx(path, fmt, control=False):
    cases = mx_cases(fmt)
    if control:    # two cases, expected values from a model with the in-array accumulator rounding changed RNE -> RTZ
        cases = [c for c in cases if c[0] in (f"gaussian_64x64x1024", f"laplace_64x64x1024")]
        assert len(cases) == 2
    quad = fmt == "fp4"
    lines = ["// Generated by refmodel/export_m7a.py mx. Do not edit.", "#include <stdint.h>",
             "typedef struct { const char *name; int M, N, K; const uint8_t *A; const uint8_t *B; const uint8_t *Asc; const uint8_t *Bsc; const uint16_t *C; } case_t;",
             f"#define NCASES {len(cases)}"]
    maxab = 0
    info = []
    saved = mx.rne_fmt
    if control:
        mx.rne_fmt = rtz_fmt
    try:
        for n, (name, dist, M, N, K, seed, recipe) in enumerate(cases):
            a, b = mx_inputs(dist, M, N, K, seed)
            qa, qb = mx.quantize(a, fmt, recipe), mx.quantize(b.T, fmt, recipe)
            _, bits = mx.hw_matmul(qa, qb, return_bits=True)
            ca, cb = qa.codes[:, :K].astype(np.uint8), qb.codes[:, :K].astype(np.uint8)       # (M,K), (N,K)
            if quad:
                a_hw = ((ca[1::2, :] << 4) | ca[0::2, :]).astype(np.uint8)                    # [M/2][K]
                b_hw = ((cb[1::2, :].T << 4) | cb[0::2, :].T).astype(np.uint8)                 # [K][N/2]
            else:
                a_hw, b_hw = ca, cb.T.copy()                                                   # [M][K], [K][N]
            a_sc, b_sc = qa.sc_codes.T.copy(), qb.sc_codes.T.copy()                            # [G][M], [G][N]
            maxab = max(maxab, a_hw.size, b_hw.size)
            hx = lambda v: f"0x{int(v):02x}"
            lines += [f"static const uint8_t A{n}[{a_hw.size}] = {{", _fmt(a_hw.ravel(), 32, hx), "};",
                      f"static const uint8_t B{n}[{b_hw.size}] = {{", _fmt(b_hw.ravel(), 32, hx), "};",
                      f"static const uint8_t AS{n}[{a_sc.size}] = {{", _fmt(a_sc.ravel(), 32, hx), "};",
                      f"static const uint8_t BS{n}[{b_sc.size}] = {{", _fmt(b_sc.ravel(), 32, hx), "};",
                      f"static const uint16_t C{n}[{M * N}] = {{", _fmt(bits.ravel(), 16, lambda v: f"0x{int(v):04x}"), "};"]
            nonfin = int((~np.isfinite(_bf(bits))).sum())
            info.append(f"{name}: nonfinite {nonfin}/{M * N}")
    finally:
        mx.rne_fmt = saved
    lines.append("static const case_t cases[NCASES] = {")
    lines += [f'    {{ "{c[0]}", {c[2]}, {c[3]}, {c[4]}, A{n}, B{n}, AS{n}, BS{n}, C{n} }},' for n, c in enumerate(cases)]
    lines += ["};", f"#define MAX_AB_BYTES {maxab}", ""]
    # MAX_AB_BYTES must precede its use in the C file's buffers: it is defined after the data but before main's buffers are declared
    Path(path).write_text("\n".join(lines), newline="\n")
    print(f"wrote {path} ({fmt}, {'CONTROL ' if control else ''}{len(cases)} cases): " + "; ".join(info))


def _bf(bits):
    return (np.asarray(bits, np.uint32) << 16).view(np.float32)

# ----------------------------------------------------------------------------- NVFP4 on the sweep's input distributions
def export_nvfp4(path, dist, seed, M, N, K):
    """Header for hw/tests/nvfp4_e2e_mnk.c (same layout as refmodel/export_e2e.py) from accuracy_sweep.make_inputs data."""
    import quant
    from hw_dot import hw_matmul_v0
    a, b = sw.make_inputs(dist, K, seed, M, N)
    qa, qb = quant.quantize(a), quant.quantize(b.T)
    _, out = hw_matmul_v0(qa, qb)
    ca, cb = qa.codes.astype(np.uint8), qb.codes.astype(np.uint8)
    a_hw = ((ca[1::2, :] << 4) | ca[0::2, :]).astype(np.uint8)
    b_hw = ((cb[1::2, :].T << 4) | cb[0::2, :].T).astype(np.uint8)
    a_sc, b_sc = qa.scales.T.astype(np.uint8), qb.scales.T.astype(np.uint8)
    hx = lambda v: f"0x{int(v):02x}"
    lines = ["// Generated by refmodel/export_m7a.py nvfp4. Do not edit.",
             f"// NVFP4 end-to-end case on sweep inputs: {dist}, seed {seed}, A {M}x{K} times B {K}x{N}.",
             "#ifndef NVFP4_M7A_DATA_H", "#define NVFP4_M7A_DATA_H", "#include <stdint.h>",
             f"#define E2E_M {M}", f"#define E2E_K {K}", f"#define E2E_N {N}",
             f"static const uint8_t A_in_hw[{M // 2}][{K}] = {{", _fmt(a_hw.ravel(), 16, hx), "};",
             f"static const uint8_t B_in[{K}][{N // 2}] = {{", _fmt(b_hw.ravel(), 16, hx), "};",
             f"static const uint8_t A_sc[{K // 16}][{M}] = {{", _fmt(a_sc.ravel(), 16, hx), "};",
             f"static const uint8_t B_sc[{K // 16}][{N}] = {{", _fmt(b_sc.ravel(), 16, hx), "};",
             f"static const float tA = {float(qa.tensor_scale[0]).hex()}f;", f"static const float tB = {float(qb.tensor_scale[0]).hex()}f;",
             f"static const uint32_t out_bits[{M}][{N}] = {{", _fmt(out.ravel(), 8, lambda v: f"0x{f32_bits(v):08x}u"), "};",
             "#endif", ""]
    Path(path).write_text("\n".join(lines), newline="\n")
    print(f"wrote {path}: {dist} M={M} N={N} K={K} seed={seed}, {int(np.sum(out == 0))} zero outputs, out range [{out.min():.4g}, {out.max():.4g}]")


if __name__ == "__main__":
    what = sys.argv[1]
    if what == "int8":
        export_int8(sys.argv[2])
    elif what == "fp32":
        export_fp32(sys.argv[2])
    elif what == "mx":
        export_mx(sys.argv[3], sys.argv[2], control=len(sys.argv) > 4 and sys.argv[4] == "control")
    elif what == "nvfp4":
        export_nvfp4(sys.argv[2], sys.argv[3], int(sys.argv[4]), int(sys.argv[5]), int(sys.argv[6]), int(sys.argv[7]))
    else:
        raise SystemExit("unknown target " + what)
