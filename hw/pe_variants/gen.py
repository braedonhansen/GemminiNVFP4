#!/usr/bin/env python3
"""Generate V1/V2 (case tables) and the iverilog testbenches from the golden JSON.

Run: python3 gen.py
Golden: refmodel/vectors/e2m1_pairs.json (doubled E2M1 values, product 9-bit two's complement).
"""
import json, os
here = os.path.dirname(os.path.abspath(__file__))
root = os.path.abspath(os.path.join(here, "..", ".."))
gold = json.load(open(os.path.join(root, "refmodel", "vectors", "e2m1_pairs.json")))
assert len(gold) == 256
G = {(r["a"], r["b"]): r for r in gold}


def w(path, s):
    with open(path, "w", newline="\n") as f:
        f.write(s)


PE_PORTS = """  input  [3:0] a0, a1, w0, w1,
  input  [12:0] c00, c01, c10, c11,
  output [12:0] d00, d01, d10, d11"""
PE_BODY = """  wire [8:0] p00, p01, p10, p11;
  mul_{v} u00 (.a(a0), .w(w0), .p(p00));
  mul_{v} u01 (.a(a0), .w(w1), .p(p01));
  mul_{v} u10 (.a(a1), .w(w0), .p(p10));
  mul_{v} u11 (.a(a1), .w(w1), .p(p11));
  assign d00 = c00 + {{{{4{{p00[8]}}}}, p00}};
  assign d01 = c01 + {{{{4{{p01[8]}}}}, p01}};
  assign d10 = c10 + {{{{4{{p10[8]}}}}, p10}};
  assign d11 = c11 + {{{{4{{p11[8]}}}}, p11}};
"""

# ---- V1: full 256-entry LUT, signed 9-bit product
s = "// V1: full LUT. case({a,w}) with 256 entries -> signed 9-bit product (GENERATED by gen.py)\n"
s += "module mul_v1 (input [3:0] a, input [3:0] w, output reg [8:0] p);\n  always @* begin\n    case ({a, w})\n"
for a in range(16):
    for b in range(16):
        s += "      8'h%02x: p = 9'h%03x;\n" % (a * 16 + b, G[(a, b)]["product_9bit"])
s += "      default: p = 9'h000;\n    endcase\n  end\nendmodule\n\n"
s += "module pe_v1 (\n" + PE_PORTS + ");\n" + PE_BODY.format(v="v1") + "endmodule\n"
w(os.path.join(here, "v1_full_lut.v"), s)

# ---- V2: 64-entry magnitude LUT on {a[2:0],w[2:0]}, sign XOR, negate
MAGS = [0, 1, 2, 3, 4, 6, 8, 12]
s = "// V2: magnitude LUT (64 entries on {a[2:0],w[2:0]}) + sign XOR + two's-complement negate (GENERATED by gen.py)\n"
s += "module mul_v2 (input [3:0] a, input [3:0] w, output [8:0] p);\n  reg [7:0] mag;\n  always @* begin\n    case ({a[2:0], w[2:0]})\n"
for a in range(8):
    for b in range(8):
        s += "      6'h%02x: mag = 8'd%d;\n" % (a * 8 + b, MAGS[a] * MAGS[b])
s += "      default: mag = 8'd0;\n    endcase\n  end\n"
s += "  wire s = a[3] ^ w[3];\n  assign p = s ? (9'd0 - {1'b0, mag}) : {1'b0, mag};\nendmodule\n\n"
s += "module pe_v2 (\n" + PE_PORTS + ");\n" + PE_BODY.format(v="v2") + "endmodule\n"
w(os.path.join(here, "v2_mag_lut.v"), s)

# ---- testbenches (module name via -DV=..., golden path via -DGOLD=...)
tbm = """// GENERATED by gen.py. Exhaustive: all 256 (a,w) vs golden e2m1_pairs.hex (9-bit two's complement).
`timescale 1ns/1ps
module tb;
  reg [8:0] gold [0:255];
  reg [3:0] a, w;
  wire [8:0] p;
  integer i, errs;
  `MULMOD dut (.a(a), .w(w), .p(p));
  initial begin
    $readmemh(`GOLD, gold);
    errs = 0;
    for (i = 0; i < 256; i = i + 1) begin
      a = i[7:4]; w = i[3:0]; #1;
      if (p !== gold[i]) begin errs = errs + 1; if (errs < 10) $display("MISMATCH a=%h w=%h got=%h exp=%h", a, w, p, gold[i]); end
    end
    $display("RESULT %0s checked=256 mismatches=%0d", `NAME, errs);
    $finish;
  end
endmodule
"""
tbp = """// GENERATED by gen.py. Exhaustive: all 65536 (a0,a1,w0,w1) x 6 c-sets, vs golden-derived expectation mod 2^13.
`timescale 1ns/1ps
module tb;
  reg [8:0] gold [0:255];
  reg [3:0] a0, a1, w0, w1;
  reg [12:0] c00, c01, c10, c11;
  wire [12:0] d00, d01, d10, d11;
  integer i, k, errs, n;
  reg [12:0] e00, e01, e10, e11;
  `PEMOD dut (.a0(a0), .a1(a1), .w0(w0), .w1(w1), .c00(c00), .c01(c01), .c10(c10), .c11(c11),
             .d00(d00), .d01(d01), .d10(d10), .d11(d11));
  function [12:0] sx(input [8:0] x); sx = {{4{x[8]}}, x}; endfunction
  initial begin
    $readmemh(`GOLD, gold);
    errs = 0; n = 0;
    for (k = 0; k < 6; k = k + 1) begin
      for (i = 0; i < 65536; i = i + 1) begin
        a0 = i[15:12]; a1 = i[11:8]; w0 = i[7:4]; w1 = i[3:0];
        case (k)
          0: begin c00 = 0; c01 = 0; c10 = 0; c11 = 0; end
          1: begin c00 = 13'd3951; c01 = 13'd3951; c10 = 13'd3951; c11 = 13'd3951; end        // +4095-144
          2: begin c00 = 13'h1090; c01 = 13'h1090; c10 = 13'h1090; c11 = 13'h1090; end        // -4096+144 = -3952
          3: begin c00 = 13'd3951; c01 = 13'h1090; c10 = 13'h1090; c11 = 13'd3951; end
          default: begin c00 = $random; c01 = $random; c10 = $random; c11 = $random; end
        endcase
        #1;
        e00 = c00 + sx(gold[{a0, w0}]); e01 = c01 + sx(gold[{a0, w1}]);
        e10 = c10 + sx(gold[{a1, w0}]); e11 = c11 + sx(gold[{a1, w1}]);
        n = n + 1;
        if (d00 !== e00 || d01 !== e01 || d10 !== e10 || d11 !== e11) begin
          errs = errs + 1;
          if (errs < 10) $display("MISMATCH k=%0d a=%h%h w=%h%h c=%h %h %h %h got=%h %h %h %h exp=%h %h %h %h",
            k, a0, a1, w0, w1, c00, c01, c10, c11, d00, d01, d10, d11, e00, e01, e10, e11);
        end
      end
    end
    $display("RESULT %0s checked=%0d mismatches=%0d", `NAME, n, errs);
    $finish;
  end
endmodule
"""
os.makedirs(os.path.join(here, "tb"), exist_ok=True)
w(os.path.join(here, "tb", "tb_mul.v"), tbm)
w(os.path.join(here, "tb", "tb_pe.v"), tbp)
print("generated")
