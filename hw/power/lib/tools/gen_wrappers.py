#!/usr/bin/env python3
"""Generate Chipyard-compatible *_ext wrapper modules built from OpenRAM banks (M7.P0b).

Each wrapper keeps the exact port list Chisel/firtool gives the SRAM black box, and
instantiates N_deep x N_wide copies of one OpenRAM bank macro. Only the bank row selected
by the high address bits gets csb low, so one bank row is active per access.
Bank-select registers and the read-data mux are plain logic that synthesis will count.

usage: gen_wrappers.py OUTDIR      (writes <design>/<ext>.v for every design in DESIGNS)
"""
import os, sys, math

# kind: 'rw' = Chisel "mrw"/"rw" (1 RW port, wmode, wmask) -> OpenRAM 1rw bank
#       'wr' = Chisel "mwrite,read" / "write,read" (1W + 1R) -> OpenRAM 1w1r bank
# mask_gran = bits per write-mask bit on the *external* port (None = no mask port)
# bank: (module name, depth, width, bank_mask_bits or None)
BK_1RW = ("bk_1rw_256x128_ws8", 256, 128, 16)
BK_1W1R_SPAD = ("bk_1w1r_256x128_ws8", 256, 128, 16)
BK_ACC8 = ("bk_1w1r_64x512_ws8", 64, 512, 64)
BK_ACC256 = ("bk_1w1r_64x512_ws256", 64, 512, 2)
BK_SCALE = ("bk_1w1r_128x128_nomask", 128, 128, None)


def E(name, depth, width, kind, mask_gran, bank, count, role, derived=False):
    return dict(name=name, depth=depth, width=width, kind=kind, mask_gran=mask_gran,
                bank=bank, count=count, role=role, derived=derived)


DESIGNS = {
    "int8": [  # elaborated: ~/chipyard GemminiRocketConfig
        E("mem_ext", 4096, 128, "rw", 8, BK_1RW, 4, "scratchpad bank (spad_mems_0..3)"),
        E("mem_0_ext", 512, 512, "wr", 8, BK_ACC8, 2, "accumulator bank (acc_mems_0..1)"),
    ],
    "mxfp4": [  # elaborated: ~/chipyard-mx MxFp4OnlyGemminiRocketConfig
        E("mem_ext", 4096, 128, "wr", 8, BK_1W1R_SPAD, 4, "scratchpad bank"),
        E("banks_0_ext", 256, 512, "wr", 256, BK_ACC256, 4, "accumulator sub-bank (2 acc_mems x 2 banks)"),
        E("banks_0_0_ext", 128, 128, "wr", None, BK_SCALE, 8, "shared scale memory bank"),
    ],
    "nvfp4": [  # elaborated: ~/chipyard-mx NvFp4GemminiRocketConfig
        E("mem_ext", 4096, 128, "wr", 8, BK_1W1R_SPAD, 4, "scratchpad bank"),
        E("banks_0_ext", 256, 1024, "wr", 256, BK_ACC256, 4, "accumulator sub-bank (2 acc_mems x 2 banks)"),
        E("banks_0_0_ext", 128, 128, "wr", None, BK_SCALE, 8, "shared scale memory bank"),
    ],
    "mxfp8": [  # NOT elaborated; derived by analogy with mxfp4 (same standaloneMxFPConfig base)
        E("mem_ext", 4096, 128, "wr", 8, BK_1W1R_SPAD, 4, "scratchpad bank", True),
        E("banks_0_ext", 256, 512, "wr", 256, BK_ACC256, 4, "accumulator sub-bank", True),
        E("banks_0_0_ext", 128, 128, "wr", None, BK_SCALE, 8, "shared scale memory bank", True),
    ],
    "fp32": [  # NOT elaborated; derived from GemminiFP32DefaultConfig (DIM 4, 256 KiB spad, 64 KiB acc)
        E("mem_ext", 4096, 128, "rw", 8, BK_1RW, 4, "scratchpad bank (derived)", True),
        E("mem_0_ext", 4096, 128, "wr", 8, BK_1W1R_SPAD, 1, "accumulator bank (derived, 1 bank)", True),
    ],
}


def ports(e):
    d, w = e["depth"], e["width"]
    aw = int(math.log2(d))
    p = []  # (dir, width, name)
    mg = e["mask_gran"]
    nm = w // mg if mg else 0
    if e["kind"] == "rw":
        p += [("input", aw, "RW0_addr"), ("input", 1, "RW0_clk"), ("input", w, "RW0_wdata"),
              ("output", w, "RW0_rdata"), ("input", 1, "RW0_en"), ("input", 1, "RW0_wmode")]
        if nm:
            p.append(("input", nm, "RW0_wmask"))
    else:
        p += [("input", aw, "R0_addr"), ("input", 1, "R0_clk"), ("output", w, "R0_data"),
              ("input", 1, "R0_en"), ("input", aw, "W0_addr"), ("input", 1, "W0_clk"),
              ("input", w, "W0_data"), ("input", 1, "W0_en")]
        if nm:
            p.append(("input", nm, "W0_mask"))
    return p


def rng(wd):
    return "" if wd == 1 else "[%d:0] " % (wd - 1)


def gen(e):
    d, w = e["depth"], e["width"]
    bname, bd, bw, bmask = e["bank"]
    nd, nw = d // bd, w // bw
    assert d % bd == 0 and w % bw == 0, e
    aw = int(math.log2(d))
    baw = int(math.log2(bd))
    selw = int(math.log2(nd)) if nd > 1 else 0
    mg = e["mask_gran"]
    nm = (w // mg) if mg else 0
    if bmask is not None:
        assert nm // nw == bmask, (e["name"], nm, nw, bmask)
    else:
        assert nm == 0, e["name"]
    L = []
    L.append("// Generated by hw/power/lib/tools/gen_wrappers.py (M7.P0b). Do not edit.")
    L.append("// %s: %dx%d %s, mask_gran %s = %d x %d OpenRAM banks (%s, %dx%d)%s" % (
        e["name"], d, w, "1RW" if e["kind"] == "rw" else "1W+1R", mg, nd, nw, bname, bd, bw,
        "  [DERIVED, not elaborated]" if e["derived"] else ""))
    if nd > 1:
        L.append("// Only the bank row selected by addr[%d:%d] gets csb low: one bank row is active per access." % (aw - 1, baw))
    L.append("module %s(" % e["name"])
    pl = ports(e)
    L.append(",\n".join("  %s %s%s" % (dr, rng(wd), nmn) for dr, wd, nmn in pl))
    L.append(");")
    if e["kind"] == "rw":
        wen = "RW0_en & RW0_wmode"
        ren = "RW0_en & ~RW0_wmode"
        wadr = radr = "RW0_addr"
        wclk = rclk = "RW0_clk"
        wdat, wmask, rout = "RW0_wdata", "RW0_wmask", "RW0_rdata"
    else:
        wen = "W0_en"
        ren = "R0_en"
        wadr, radr = "W0_addr", "R0_addr"
        wclk, rclk = "W0_clk", "R0_clk"
        wdat, wmask, rout = "W0_data", "W0_mask", "R0_data"
    if nd > 1:
        L.append("  reg [%d:0] rsel_q;" % (selw - 1))
        L.append("  always @(posedge %s) if (%s) rsel_q <= %s[%d:%d];" % (rclk, ren, radr, aw - 1, baw))
    L.append("  wire [%d:0] dout_all;" % (nd * w - 1))
    for i in range(nd):
        wsel = "(%s[%d:%d] == %d'd%d)" % (wadr, aw - 1, baw, selw, i) if nd > 1 else "1'b1"
        rsel = "(%s[%d:%d] == %d'd%d)" % (radr, aw - 1, baw, selw, i) if nd > 1 else "1'b1"
        for j in range(nw):
            lo, hi = j * bw, (j + 1) * bw - 1
            inst = "u_b%d_%d" % (i, j)
            c = []
            if e["kind"] == "rw":
                c.append(".clk0(%s)" % wclk)
                c.append(".csb0(~(RW0_en & %s))" % wsel)
                c.append(".web0(~RW0_wmode)")
                if bmask is not None:
                    c.append(".wmask0(%s[%d:%d])" % (wmask, (j + 1) * bmask - 1, j * bmask))
                c.append(".addr0(%s[%d:0])" % (wadr, baw - 1))
                c.append(".din0(%s[%d:%d])" % (wdat, hi, lo))
                c.append(".dout0(dout_all[%d:%d])" % (i * w + hi, i * w + lo))
            else:
                c.append(".clk0(%s)" % wclk)
                c.append(".csb0(~(%s & %s))" % (wen, wsel))
                if bmask is not None:
                    c.append(".wmask0(%s[%d:%d])" % (wmask, (j + 1) * bmask - 1, j * bmask))
                c.append(".addr0(%s[%d:0])" % (wadr, baw - 1))
                c.append(".din0(%s[%d:%d])" % (wdat, hi, lo))
                c.append(".clk1(%s)" % rclk)
                c.append(".csb1(~(%s & %s))" % (ren, rsel))
                c.append(".addr1(%s[%d:0])" % (radr, baw - 1))
                c.append(".dout1(dout_all[%d:%d])" % (i * w + hi, i * w + lo))
            L.append("  %s %s (\n    %s\n  );" % (bname, inst, ",\n    ".join(c)))
    if nd > 1:
        L.append("  assign %s = dout_all[rsel_q*%d +: %d];" % (rout, w, w))
    else:
        L.append("  assign %s = dout_all;" % rout)
    L.append("endmodule\n")
    return "\n".join(L)


def main():
    out = sys.argv[1]
    n = 0
    for des, ents in DESIGNS.items():
        os.makedirs(os.path.join(out, des), exist_ok=True)
        for e in ents:
            with open(os.path.join(out, des, e["name"] + ".v"), "w", newline="\n") as f:
                f.write(gen(e))
                n += 1
    print("wrote", n, "wrapper files")
    assert n > 0


if __name__ == "__main__":
    main()
